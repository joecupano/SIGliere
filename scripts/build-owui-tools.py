#!/usr/bin/env python3
"""Build self-contained Open WebUI tool files from thin wrappers + sigliere_core.

Open WebUI tools are pasted into Workspace -> Tools and run inside the Open
WebUI container, which has no repo checkout, so they cannot import
sigliere_core. Each wrapper in openwebui-tools/src/ imports what it needs from
sigliere_core; this script inlines those modules into one flat file at
openwebui-tools/<same name>.py.

Usage:
  scripts/build-owui-tools.py           write the generated tools
  scripts/build-owui-tools.py --check   exit 1 if any generated tool is stale
"""

import argparse
import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CORE_DIR = REPO / "sigliere_core"
SRC_DIR = REPO / "openwebui-tools" / "src"
OUT_DIR = REPO / "openwebui-tools"
CORE_PKG = "sigliere_core"

GENERATED_NOTE = (
    "# GENERATED by scripts/build-owui-tools.py from openwebui-tools/src/{name}\n"
    "# and sigliere_core/. DO NOT EDIT: change the source and rebuild.\n"
)


def _core_imports(tree: ast.Module) -> list:
    """Top-level `from sigliere_core[.mod] import ...` nodes, as
    (node, [module names needed])."""
    found = []
    for node in tree.body:
        if not isinstance(node, ast.ImportFrom) or node.level != 0:
            continue
        if node.module == CORE_PKG:
            found.append((node, [a.name for a in node.names]))
        elif node.module and node.module.startswith(CORE_PKG + "."):
            found.append((node, [node.module.split(".", 1)[1]]))
    return found


def _drop_lines(lines: list, nodes: list) -> list:
    """Source lines with the given statements removed."""
    dead = set()
    for node in nodes:
        dead.update(range(node.lineno - 1, node.end_lineno))
    return [ln for i, ln in enumerate(lines) if i not in dead]


def _module_order(wanted: list) -> list:
    """Core modules to inline, dependencies first, each once."""
    order: list = []

    def visit(mod: str) -> None:
        if mod in order:
            return
        path = CORE_DIR / f"{mod}.py"
        if not path.is_file():
            raise SystemExit(f"error: {CORE_PKG}.{mod} not found ({path})")
        for _, deps in _core_imports(ast.parse(path.read_text())):
            for dep in deps:
                visit(dep)
        order.append(mod)

    for mod in wanted:
        visit(mod)
    return order


def _inline_module(mod: str) -> str:
    """A core module's source minus its docstring and sigliere_core imports."""
    text = (CORE_DIR / f"{mod}.py").read_text()
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)
    drop = [n for n, _ in _core_imports(tree)]
    if (tree.body and isinstance(tree.body[0], ast.Expr)
            and isinstance(getattr(tree.body[0], "value", None), ast.Constant)
            and isinstance(tree.body[0].value.value, str)):
        drop.append(tree.body[0])
    body = "".join(_drop_lines(lines, drop)).strip("\n")
    banner = f"# ---- inlined from {CORE_PKG}/{mod}.py " + "-" * 24
    return f"{banner}\n{body}\n"


def build(src: Path) -> str:
    text = src.read_text()
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)

    core = _core_imports(tree)
    if not core:
        raise SystemExit(f"error: {src.name} imports nothing from {CORE_PKG}")
    wanted = [m for _, mods in core for m in mods]
    modules = _module_order(wanted)

    if not (tree.body and isinstance(tree.body[0], ast.Expr)):
        raise SystemExit(f"error: {src.name} must start with the tool docstring")
    doc_end = tree.body[0].end_lineno

    imports = [n for n in tree.body if isinstance(n, (ast.Import, ast.ImportFrom))]
    if not imports:
        raise SystemExit(f"error: {src.name} has no imports")
    last_import = max(n.end_lineno for n in imports)

    kept = _drop_lines(lines, [n for n, _ in core])
    # Line numbers shift once dropped imports are removed; recompute the
    # insertion point (just after the last remaining import) on the kept text.
    removed_before = sum(
        n.end_lineno - n.lineno + 1 for n, _ in core if n.end_lineno <= last_import
    )
    insert_at = last_import - removed_before
    inlined = "\n\n".join(_inline_module(m) for m in modules)

    out = (
        "".join(kept[:doc_end])
        + GENERATED_NOTE.format(name=src.name)
        + "".join(kept[doc_end:insert_at]).rstrip("\n")
        + "\n\n\n" + inlined
        + "\n\n" + "".join(kept[insert_at:]).lstrip("\n")
    )
    ast.parse(out)  # the result must be valid Python
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="verify generated tools are up to date; write nothing")
    args = ap.parse_args()

    stale = []
    for src in sorted(SRC_DIR.glob("*.py")):
        built = build(src)
        dest = OUT_DIR / src.name
        if args.check:
            if not dest.is_file() or dest.read_text() != built:
                stale.append(dest.relative_to(REPO))
        else:
            dest.write_text(built)
            print(f"built {dest.relative_to(REPO)}")
    if stale:
        print("stale generated tools (run scripts/build-owui-tools.py):", file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
